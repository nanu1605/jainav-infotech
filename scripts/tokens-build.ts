/**
 * pnpm tokens:build — brand.config.ts → tokens.css + tokens.generated.ts (spec §5.2).
 * Fails (and writes nothing) if any contrast pair misses its target in either theme.
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { converter, formatHex, formatHex8, parse, toGamut, wcagContrast } from 'culori'

import {
  brandConfig,
  semanticColorNames,
  type BrandConfig,
  type ColorRef,
  type ScaleName,
  type SemanticColor,
} from '../src/styles/brand.config'

const toOklch = converter('oklch')
const toSrgb = toGamut('rgb', 'oklch')

/** step → [OKLCH lightness, chroma factor applied to the seed's chroma] */
const COLOR_STEPS: Record<number, [number, number]> = {
  50: [0.975, 0.12],
  100: [0.94, 0.25],
  200: [0.88, 0.45],
  300: [0.8, 0.7],
  400: [0.71, 0.9],
  500: [0.62, 1],
  600: [0.54, 1],
  700: [0.46, 0.92],
  800: [0.38, 0.8],
  900: [0.3, 0.65],
  950: [0.24, 0.5],
}
const NEUTRAL_STEPS: Record<number, [number, number]> = {
  0: [1, 0],
  50: [0.985, 0.5],
  100: [0.965, 0.7],
  200: [0.925, 0.85],
  300: [0.87, 1],
  400: [0.72, 1],
  500: [0.56, 1],
  600: [0.47, 1],
  700: [0.39, 1],
  800: [0.31, 1],
  900: [0.24, 1],
  950: [0.2, 1],
  1000: [0.16, 1],
}

/** [foreground, background, minimum ratio] — checked in both themes. */
export const CONTRAST_RULES: Array<[SemanticColor, SemanticColor, number]> = [
  // Body text ≥ 4.5:1
  ...(['bg', 'bg-subtle', 'surface', 'surface-raised'] as const).flatMap(
    (bg) =>
      [
        ['fg', bg, 4.5],
        ['fg-muted', bg, 4.5],
      ] as Array<[SemanticColor, SemanticColor, number]>,
  ),
  ['fg-inverse', 'fg', 4.5],
  // Text on filled actions and status surfaces ≥ 4.5:1
  ['primary-fg', 'primary', 4.5],
  ['primary-fg', 'primary-hover', 4.5],
  ['brand-accent-fg', 'brand-accent', 4.5],
  ['success-fg', 'success', 4.5],
  ['warning-fg', 'warning', 4.5],
  ['danger-fg', 'danger', 4.5],
  ['info-fg', 'info', 4.5],
  // Large text and UI elements (input borders, focus ring, icons) ≥ 3:1
  ...(['bg', 'surface'] as const).flatMap(
    (bg) =>
      [
        ['border-strong', bg, 3],
        ['ring', bg, 3],
        ['fg-subtle', bg, 3],
        ['primary', bg, 3],
      ] as Array<[SemanticColor, SemanticColor, number]>,
  ),
]

const cssScaleName = (scale: string) => scale.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)

function buildScale(seed: string, steps: Record<number, [number, number]>) {
  const base = toOklch(parse(seed))
  if (!base) throw new Error(`Invalid seed color: ${seed}`)
  const scale: Record<string, string> = {}
  for (const [step, [l, chromaFactor]] of Object.entries(steps)) {
    scale[step] = formatHex(
      toSrgb({ mode: 'oklch', l, c: (base.c ?? 0) * chromaFactor, h: base.h }),
    )
  }
  return scale
}

export function buildTokens(config: BrandConfig) {
  const scales = Object.fromEntries(
    Object.entries(config.seeds).map(([name, seed]) => [
      name,
      buildScale(seed, name === 'neutral' ? NEUTRAL_STEPS : COLOR_STEPS),
    ]),
  ) as Record<ScaleName, Record<string, string>>

  const resolve = (ref: ColorRef) => {
    const { key, alpha } =
      typeof ref === 'string' ? { key: ref, alpha: 1 } : { key: ref.ref, alpha: ref.alpha }
    const [scale, step] = key.split('.') as [ScaleName, string]
    const hex = scales[scale]?.[step]
    if (!hex) throw new Error(`Unknown color reference: ${key}`)
    const cssVar = `var(--${cssScaleName(scale)}-${step})`
    return alpha === 1
      ? { hex, css: cssVar }
      : {
          hex: formatHex8({ ...parse(hex)!, alpha }),
          css: `color-mix(in oklch, ${cssVar} ${Math.round(alpha * 100)}%, transparent)`,
        }
  }

  const themes = (['light', 'dark'] as const).map((name) => {
    const mapping = config[name]
    const colors = Object.fromEntries(
      semanticColorNames.map((token) => [token, resolve(mapping.colors[token])]),
    ) as Record<SemanticColor, { hex: string; css: string }>
    const shadowBase = resolve(mapping.shadowColor).css
    return { name, mapping, colors, shadowBase }
  })

  const failures: string[] = []
  for (const { name, colors } of themes) {
    for (const [fg, bg, min] of CONTRAST_RULES) {
      const ratio = wcagContrast(colors[fg].hex, colors[bg].hex)
      if (ratio < min)
        failures.push(`${name}: --${fg} on --${bg} = ${ratio.toFixed(2)}:1 (needs ${min}:1)`)
    }
  }

  const header = 'GENERATED by `pnpm tokens:build` from src/styles/brand.config.ts. Do not edit.'
  const shadowNames = Object.keys(config.shadows) as Array<keyof BrandConfig['shadows']>

  const themeBlock = ({ name, mapping, colors, shadowBase }: (typeof themes)[number]) => [
    ...semanticColorNames.map((token) => `  --${token}: ${colors[token].css};`),
    ...mapping.gradients.map((g, i) => `  --gradient-${i + 1}: ${g};`),
    ...shadowNames.map(
      (s) =>
        `  --shadow-color-${s}: color-mix(in oklch, ${shadowBase} ${config.shadows[s][name]}%, transparent);`,
    ),
    `  color-scheme: ${name};`,
  ]

  const css = [
    `/* ${header} */`,
    '',
    '@theme static {',
    '  --radius-*: initial;',
    '  --ease-*: initial;',
    '  --shadow-*: initial;',
    ...Object.entries(config.radius).map(([k, v]) => `  --radius-${k}: ${v};`),
    ...Object.entries(config.motion).map(([k, v]) => `  --${k}: ${v};`),
    ...shadowNames.map(
      (s) => `  --shadow-${s}: ${config.shadows[s].geometry} var(--shadow-color-${s});`,
    ),
    '}',
    '',
    ':root {',
    ...Object.entries(scales).flatMap(([scale, steps]) =>
      Object.entries(steps).map(([step, hex]) => `  --${cssScaleName(scale)}-${step}: ${hex};`),
    ),
    '',
    ...themeBlock(themes[0]),
    '}',
    '',
    "[data-theme='dark'] {",
    ...themeBlock(themes[1]),
    '}',
    '',
  ].join('\n')

  const hexMap = (t: (typeof themes)[number]) =>
    Object.fromEntries(semanticColorNames.map((token) => [token, t.colors[token].hex]))
  const ts = [
    `// ${header}`,
    '// Semantic colors as hex for emails, share images, invoice PDFs and admin branding.',
    '',
    `export const tokens = ${JSON.stringify({ light: hexMap(themes[0]), dark: hexMap(themes[1]) }, null, 2)} as const`,
    '',
    'export type SemanticToken = keyof typeof tokens.light',
    '',
  ].join('\n')

  return { css, ts, failures }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const { css, ts, failures } = buildTokens(brandConfig)
  if (failures.length) {
    console.error(`Contrast check failed — tokens not written:\n  ${failures.join('\n  ')}`)
    process.exit(1)
  }
  const stylesDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/styles')
  writeFileSync(path.join(stylesDir, 'tokens.css'), css)
  writeFileSync(path.join(stylesDir, 'tokens.generated.ts'), ts)
  console.log('tokens.css and tokens.generated.ts written; all contrast pairs pass.')
}
