/**
 * pnpm check:tokens — colors may only come from brand.config.ts via tokens (spec §3, §5.2).
 * Fails on color literals, Tailwind default palette classes and arbitrary color values.
 */
import { readdirSync, readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SCAN_DIRS = ['src']
const EXTENSIONS = /\.(?:tsx?|jsx?|mjs|cjs|css|scss|mdx?)$/
const ALLOWED = new Set([
  'src/styles/brand.config.ts',
  'src/styles/tokens.css',
  'src/styles/tokens.generated.ts',
  'src/payload-types.ts',
])
// Generated by Payload; never hand-styled.
const SKIPPED_DIRS = ['src/app/(payload)/', 'src/migrations/']

const PALETTE =
  'slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose'
const PREFIXES =
  'bg|text|border(?:-[trblxyse])?|ring(?:-offset)?|outline|fill|stroke|from|via|to|decoration|divide|placeholder|caret|accent|shadow|inset-shadow|drop-shadow|text-shadow'

const RULES: Array<[RegExp, string]> = [
  // ponytail: hex regex can't tell `#fade` the color from an `href="#fade"` anchor; rename the anchor if hit.
  [/#(?:[0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{3,4})\b/i, 'hex color literal'],
  [/\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch)\(/i, 'color function literal'],
  [
    new RegExp(`(?<![\\w-])(?:${PREFIXES})-(?:${PALETTE})-\\d{2,3}\\b`),
    'Tailwind default palette class',
  ],
  [new RegExp(`(?<![\\w-])(?:${PREFIXES})-(?:black|white)\\b`), 'Tailwind default palette class'],
  [
    /(?<![\w-])[a-z-]+-\[(?:#|(?:rgba?|hsla?|oklch|oklab|lab|lch|hwb)\(|color:)/i,
    'arbitrary color value',
  ],
]

export function findTokenViolations(content: string, file: string): string[] {
  const out: string[] = []
  content.split(/\r?\n/).forEach((line, i) => {
    for (const [re, label] of RULES) {
      const m = line.match(re)
      if (m) out.push(`${file}:${i + 1}: ${label} "${m[0]}"`)
    }
  })
  return out
}

function* walk(dir: string): Generator<string> {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) yield* walk(full)
    else if (EXTENSIONS.test(entry.name)) yield full
  }
}

export function scan(root = ROOT): string[] {
  const violations: string[] = []
  for (const dir of SCAN_DIRS) {
    for (const full of walk(path.join(root, dir))) {
      const rel = path.relative(root, full).split(path.sep).join('/')
      if (ALLOWED.has(rel) || SKIPPED_DIRS.some((d) => rel.startsWith(d))) continue
      violations.push(...findTokenViolations(readFileSync(full, 'utf8'), rel))
    }
  }
  return violations
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const violations = scan()
  if (violations.length) {
    console.error(
      `check:tokens failed. Use token utilities (bg-primary, text-fg-muted…); colors live only in src/styles/brand.config.ts.\n  ${violations.join('\n  ')}`,
    )
    process.exit(1)
  }
  console.log('check:tokens passed.')
}
